import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { LOG_FILE_PATH } from "./logger.js";

const SERVER_URL = "http://localhost:3000";
const UPLOADS_DIR = path.resolve("uploads");

async function createTestImage(name: string) {
  const filePath = path.join(UPLOADS_DIR, name);
  await sharp({
    create: {
      width: 800,
      height: 600,
      channels: 3,
      background: { r: 100, g: 180, b: 240 },
    },
  })
    .jpeg()
    .toFile(filePath);
}

async function runCorrelationTest() {
  console.log("\n==================================================================");
  console.log("   🧪 PHASE 13: CORRELATION ID TRACING VERIFICATION TEST          ");
  console.log("==================================================================\n");

  // Create sample image for Alice and Charlie
  await createTestImage("corr-alice-photo.jpg");
  await createTestImage("corr-charlie-photo.jpg");

  const testRequests = [
    {
      user: "Alice",
      image: "corr-alice-photo.jpg",
      customCorrId: "corr-alice-custom-777",
      expectedStatus: "completed",
    },
    {
      user: "Bob (Poison Pill)",
      image: "ghost-corrupt-image.jpg", // Missing file -> Fatal error
      customCorrId: undefined,          // Auto-generated by middleware
      expectedStatus: "failed",
    },
    {
      user: "Charlie",
      image: "corr-charlie-photo.jpg",
      customCorrId: "corr-charlie-custom-999",
      expectedStatus: "completed",
    },
  ];

  console.log("📤 Step 1: Firing 3 concurrent requests with Correlation IDs...");
  const submitted: { user: string; correlationId: string; jobId: string; expected: string }[] = [];

  for (const item of testRequests) {
    const headers: Record<string, string> = {
      "Content-Type": "application/json",
      "X-API-Key": "key_std_prod_123",
    };
    if (item.customCorrId) {
      headers["X-Correlation-Id"] = item.customCorrId;
    }

    const res = await fetch(`${SERVER_URL}/jobs`, {
      method: "POST",
      headers,
      body: JSON.stringify({ image: item.image, priority: 5 }),
    });

    const corrIdFromHeader = res.headers.get("x-correlation-id") || "N/A";
    const data = (await res.json()) as any;

    submitted.push({
      user: item.user,
      correlationId: corrIdFromHeader,
      jobId: data.id,
      expected: item.expectedStatus,
    });

    console.log(
      `   ✓ ${item.user.padEnd(20)} -> HTTP ${res.status} | Correlation-ID: [${corrIdFromHeader}] | Job ID: [${data.id}]`
    );
  }

  // Wait for worker to finish
  console.log("\n⏳ Step 2: Waiting 4 seconds for worker to process and write structured logs...");
  await new Promise((r) => setTimeout(r, 4000));

  // Step 3: Inspect logs/jobs.jsonl
  console.log("\n🔍 Step 3: Querying logs/jobs.jsonl by Correlation ID...\n");
  if (!fs.existsSync(LOG_FILE_PATH)) {
    console.error("❌ Log file does not exist yet at", LOG_FILE_PATH);
    return;
  }

  const rawLines = fs.readFileSync(LOG_FILE_PATH, "utf-8").trim().split("\n");
  const parsedLogs: any[] = rawLines.map((l) => {
    try {
      return JSON.parse(l);
    } catch {
      return null;
    }
  }).filter(Boolean);

  for (const item of submitted) {
    console.log("------------------------------------------------------------------");
    console.log(`🎯 TRACING LIFECYCLE FOR: ${item.user.toUpperCase()} (${item.correlationId})`);
    console.log("------------------------------------------------------------------");

    const userLogs = parsedLogs.filter((l) => l.correlationId === item.correlationId);

    if (userLogs.length === 0) {
      console.log(`   ⚠️ No logs found for correlationId: ${item.correlationId}`);
      continue;
    }

    userLogs.forEach((log) => {
      const dur = log.durationMs !== undefined ? ` (+${log.durationMs}ms)` : "";
      const err = log.error ? ` ⚠️ Error: ${log.error.message || log.error}` : "";
      console.log(`   • [${log.level.toUpperCase().padEnd(5)}] [${log.context.padEnd(8)}] ${log.message}${dur}${err}`);
    });
  }

  console.log("\n==================================================================");
  console.log("   ✅ SUCCESS: Full request-to-worker lifecycle traced cleanly!    ");
  console.log("==================================================================\n");
}

runCorrelationTest().catch(console.error);

